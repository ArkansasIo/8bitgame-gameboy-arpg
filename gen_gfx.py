# ---- boot logo: 32x32 crest (shield + crossed swords), 16 BG tiles ----
def logo_pixels():
    W = 32
    px = [['.'] * W for _ in range(W)]
    import math
    for y in range(W):
        for x in range(W):
            # shield: flat top, curved point at bottom
            cx = x - 15.5
            if 4 <= y <= 28:
                half = 11 if y < 16 else 11 * math.sqrt(max(0, 1 - ((y - 16) / 13.0) ** 2))
                if abs(cx) <= half:
                    edge = abs(cx) > half - 1.6 or y < 5.5
                    px[y][x] = '#' if edge else ('-' if cx < -3 and y < 18 else '+')
    def put(x, y, c):
        if 0 <= x < W and 0 <= y < W: px[y][x] = c
    for y in range(2, 22):           # blade (tip at the top)
        w = 0 if y < 4 else 1
        for x in range(15 - w, 17 + w):
            put(x, y, '-')
        put(14 - w, y, '#'); put(17 + w, y, '#')
    put(15, 1, '#'); put(16, 1, '#')
    for x in range(8, 24):           # cross-guard
        put(x, 21, '#'); put(x, 22, '#')
    put(7, 21, '#'); put(24, 22, '#')
    for y in range(23, 28):          # grip + pommel
        put(15, y, '#'); put(16, y, '#')
    for x in range(14, 18):
        put(x, 28, '#'); put(x, 29, '#')
    return [''.join(r) for r in px]
