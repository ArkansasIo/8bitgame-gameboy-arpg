# Generates gfx.inc (tile data + text charmap) from ASCII pixel art.
# Legend: . = color0  - = color1  + = color2  # = color3
MAP = {'.': 0, '-': 1, '+': 2, '#': 3}

def tile(rows):
    assert len(rows) == 8, rows
    out = []
    for r in rows:
        assert len(r) == 8, r
        lo = hi = 0
        for i, ch in enumerate(r):
            v = MAP[ch]
            lo |= (v & 1) << (7 - i)
            hi |= ((v >> 1) & 1) << (7 - i)
        out += [lo, hi]
    return out

def meta16(rows):
    assert len(rows) == 16, len(rows)
    for r in rows:
        assert len(r) == 16, r
    q = lambda y, x: [r[x:x + 8] for r in rows[y:y + 8]]
    return tile(q(0, 0)) + tile(q(0, 8)) + tile(q(8, 0)) + tile(q(8, 8))

def transpose(rows):
    return [''.join(rows[y][x] for y in range(8)) for x in range(8)]

def emit(label, data):
    s = [f"{label}:"]
    for i in range(0, len(data), 16):
        s.append("    db " + ",".join(f"${b:02X}" for b in data[i:i + 16]))
    s.append(f"{label}End:")
    return "\n".join(s)

